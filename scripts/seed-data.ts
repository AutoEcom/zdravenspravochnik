import type { WorkingHours } from "../types/database"

type DaySlot = { open: string; close: string }

const closed = { closed: true, open: null, close: null }

export function hours(weekday: DaySlot, saturday?: DaySlot, sunday?: DaySlot): WorkingHours {
  const day = (slot?: DaySlot) =>
    slot ? { closed: false, open: slot.open, close: slot.close } : closed

  return {
    monday: day(weekday),
    tuesday: day(weekday),
    wednesday: day(weekday),
    thursday: day(weekday),
    friday: day(weekday),
    saturday: day(saturday),
    sunday: day(sunday),
  }
}

